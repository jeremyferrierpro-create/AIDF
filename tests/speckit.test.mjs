import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import fsp from 'node:fs/promises';
import os from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);
const BIN = path.resolve(import.meta.dirname, '..', 'bin', 'aidf.mjs');

async function run(args) {
  try {
    const { stdout, stderr } = await execFileAsync(process.execPath, [BIN, ...args], {
      env: { ...process.env, AIDF_LOG_LEVEL: 'error' },
      maxBuffer: 20 * 1024 * 1024,
    });
    return { code: 0, stdout, stderr };
  } catch (error) {
    return { code: error.code ?? 1, stdout: error.stdout ?? '', stderr: error.stderr ?? '' };
  }
}

function json(result, label) {
  try {
    return JSON.parse(result.stdout);
  } catch {
    throw new Error(`${label}: invalid JSON\n${result.stdout}\n${result.stderr}`);
  }
}

async function installedProject() {
  const root = await fsp.mkdtemp(path.join(os.tmpdir(), 'aidf-speckit-'));
  await fsp.writeFile(path.join(root, 'package.json'), JSON.stringify({ name: 'speckit-demo', version: '1.0.0' }), 'utf8');
  const install = await run(['install', '--target', root, '--adapter', 'generic', '--json']);
  assert.equal(install.code, 0, install.stderr);
  return root;
}

test('speckit status is honest when .specify is absent', async () => {
  const root = await installedProject();
  const result = await run(['speckit', 'status', '--target', root, '--json']);
  assert.equal(result.code, 0, result.stderr);
  const status = json(result, 'speckit status');
  assert.equal(status.present, false);
  assert.equal(status.status, 'ABSENT');
  assert.equal(status.constitutionPresent, false);
});

test('speckit sync refuses to overwrite an external constitution', async () => {
  const root = await installedProject();
  const target = path.join(root, '.specify', 'memory', 'constitution.md');
  await fsp.mkdir(path.dirname(target), { recursive: true });
  await fsp.writeFile(target, '# External Spec Kit constitution\n\nKeep me.\n', 'utf8');

  const result = await run(['speckit', 'sync', '--target', root, '--json']);
  assert.equal(result.code, 2, result.stderr);
  const synced = json(result, 'speckit sync');
  assert.equal(synced.status, 'CONFLICT');
  assert.match(synced.results[0].reason, /will not overwrite/);
  const after = await fsp.readFile(target, 'utf8');
  assert.match(after, /Keep me\./);
  assert.doesNotMatch(after, /AIDF:SOURCE-HASH/);
});

test('speckit sync --adopt creates a generated copy with a source hash', async () => {
  const root = await installedProject();
  await fsp.mkdir(path.join(root, '.specify'), { recursive: true });
  const result = await run(['speckit', 'sync', '--target', root, '--adopt', '--json']);
  assert.equal(result.code, 0, result.stderr);
  const synced = json(result, 'speckit sync');
  assert.equal(synced.status, 'OK');
  const file = await fsp.readFile(path.join(root, '.specify', 'memory', 'constitution.md'), 'utf8');
  assert.match(file, /AIDF:SOURCE-HASH:[a-f0-9]{64}/);
  assert.match(file, /Generated by AIDF/);
  const mapping = await fsp.readFile(path.join(root, '.specify', 'aidf', 'mapping.md'), 'utf8');
  assert.match(mapping, /AIDF constitution hash/);
});
